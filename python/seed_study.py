"""Repeat the water-profile comparison over several random seeds.

The main experiment matrix uses one fixed seed. This script regenerates the
water traces (sensor noise, spikes, missing readings) and re-runs the radio
loss model with different seeds, so the reported fixed-vs-adaptive differences
can be checked for seed sensitivity. Traces are written to a temporary folder
and deleted afterwards.

Writes experiments/results/seed_study.csv and seed_study.md.
"""
import csv
import json
import os
import shutil
import subprocess
import sys
import tempfile

import numpy as np

import analyse_results as ar
import generate_data as gd

ROOT = gd.ROOT
EXE = gd.EXE
RES = os.path.join(ROOT, "experiments", "results")


def main():
    cfg = gd.load_config()
    st_cfg = cfg["seed_study"]
    profile = st_cfg["profile"]
    pcfg = cfg["profiles"][profile]
    prof = gd.dump_profile(profile)
    radio = cfg["radio"]
    rows = []
    tmp = tempfile.mkdtemp(prefix="seed_study_")
    try:
        for seed in range(1, st_cfg["seeds"] + 1):
            for scen in st_cfg["scenarios"]:
                t, meas, faults, link, truth = gd.make_trace(prof, scen, pcfg, seed)
                tpath = os.path.join(tmp, "trace.csv")
                gd.write_csv(tpath, t, meas, faults, link, truth)
                trace = ar.read_csv(tpath)
                for strat in st_cfg["strategies"]:
                    out = os.path.join(tmp, strat)
                    os.makedirs(out, exist_ok=True)
                    cmd = [EXE, "--profile", profile, "--strategy", strat, "--trace", tpath, "--out", out,
                           "--seed", str(seed), "--loss", str(radio["loss"]), "--ack-loss", str(radio["ack_loss"]),
                           "--corrupt", str(radio["corrupt"]), "--sf", str(radio["sf"])]
                    r = subprocess.run(cmd, capture_output=True, text=True)
                    if r.returncode != 0:
                        sys.exit(r.stderr)
                    m = ar.analyse_run(out, trace, prof, pcfg, cfg["detection_tolerance_s"], cfg["event_merge_s"])
                    rows.append({"seed": seed, "scenario": scen, "strategy": strat, **m})
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    ar.write_rows(os.path.join(RES, "seed_study.csv"), rows)

    def stat(sel, key):
        v = np.array([r[key] for r in sel], dtype=float)
        v = v[~np.isnan(v)]
        return f"{v.mean():.1f} ± {v.std(ddof=1):.1f}" if len(v) > 1 else ("n/a" if len(v) == 0 else f"{v[0]:.1f}")

    table = []
    for scen in st_cfg["scenarios"]:
        for strat in st_cfg["strategies"]:
            sel = [r for r in rows if r["scenario"] == scen and r["strategy"] == strat]
            table.append({"scenario": scen, "strategy": strat,
                          "tx_attempts": stat(sel, "tx_attempts"), "energy_J": stat(sel, "energy_J"),
                          "events_detected": f"{sum(r['detected_events'] for r in sel)}/"
                                             f"{sum(r['truth_crit_events'] for r in sel)}",
                          "false_alarms": sum(r["false_alarm_episodes"] for r in sel),
                          "node_delay_s": stat(sel, "node_detect_delay_s"),
                          "gw_delay_s": stat(sel, "gateway_notify_delay_s")})
    with open(os.path.join(RES, "seed_study.md"), "w", encoding="utf-8") as f:
        f.write(f"# Seed study: {profile} profile, {st_cfg['seeds']} seeds\n\n")
        f.write("Each seed changes the trace noise/spikes/missing readings and the radio loss pattern. "
                "Values are mean ± sample standard deviation over seeds; event counts are totals. "
                "Generated by `python/seed_study.py`.\n\n")
        f.write(ar.md_table(table, list(table[0].keys())))
    print(f"wrote seed_study.csv and seed_study.md ({len(rows)} runs)")


if __name__ == "__main__":
    main()
